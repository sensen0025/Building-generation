import numpy as np
def rot_y_64(a):
    a = np.asarray(a)
    return np.transpose(a[:, :, ::-1], (2, 1, 0))
ss = np.load('/home/linux/redstone_ai/dataset/v2/ss64.npy', mmap_mode='r')
v = np.asarray(ss[250]).astype(np.int16)
nz = np.argwhere(v > 0)
print('orig bbox:', nz.min(0).tolist(), '..', nz.max(0).tolist())
vr = rot_y_64(v.copy())
nzr = np.argwhere(vr > 0)
print('rot bbox:', nzr.min(0).tolist(), '..', nzr.max(0).tolist())
print('occ same:', int((v > 0).sum()) == int((vr > 0).sum()))
# 再转回去应还原(90*4=360)
vrr = rot_y_64(rot_y_64(rot_y_64(rot_y_64(v.copy()).copy()).copy()).copy())
print('4x rot == orig:', np.array_equal(vrr, v))
print('DTYPE', v.dtype, 'negstep works')
