import os, sys
import numpy as np
from litemapy import Region, BlockState, Schematic

BASE = '/home/linux/redstone_ai'
OUT = f'{BASE}/gen_outputs'
BLOCK_MAP = f'{BASE}/dataset/v2/block_map.npy'
VOCAB = f'{BASE}/dataset/BLOCK_VOCAB_FULL.txt'

bmap = np.load(BLOCK_MAP)
vocab = [l.strip() for l in open(VOCAB, encoding='utf-8') if l.strip()]

def block_name(nid):
    oi = int(bmap[nid])
    return vocab[oi] if 0 <= oi < len(vocab) else 'minecraft:stone'

# 加载扩散模型真正生成的体素
gen_vox = np.load(f'{OUT}/gen_topk_idx4.npy')
nz = np.argwhere(gen_vox > 0)
print(f'Diffusion Generated Non-zero blocks: {len(nz)}')

min_x, min_y, min_z = nz.min(0)
max_x, max_y, max_z = nz.max(0)
W = int(max_x - min_x + 1)
H = int(max_y - min_y + 1)
L = int(max_z - min_z + 1)
print(f'Bounding box: {W}x{H}x{L}')

reg = Region(0, 0, 0, W, H, L)
counts = {}
for x in range(W):
    for y in range(H):
        for z in range(L):
            c = int(gen_vox[min_x + x, min_y + y, min_z + z])
            if c > 0:
                nm = block_name(c)
                if nm == 'minecraft:air':
                    nm = 'minecraft:stone'
                reg[x, y, z] = BlockState(nm)
                counts[nm] = counts.get(nm, 0) + 1

sch = Schematic(name='Diffusion_Generated_idx4', author='Flow_Matching_Diffusion_4k',
                description=f'Actually generated by diffusion model (Top-K confidence) {W}x{H}x{L}',
                regions={'main': reg})
sch.mc_version = 3465
out_path = f'{OUT}/actual_diffusion_generated_idx4.litematic'
sch.save(out_path)
print(f'Saved: {out_path} ({os.path.getsize(out_path)} bytes)')
print('Generated block materials:', sorted(counts.items(), key=lambda x: -x[1])[:5])
